/// Save test outputs in memory and on disk (snapshots).
///
/// Snapshots serve multiple purposes:
/// - They're used by other tests without recomputing
/// - They're compared to previous versions to detect regressions
///   - For some queries, differences between runs are OK
///   - A query is computed once per run; `DeterminismTest` checks a few for differences in the
///     same run, which signal an issue, because everything should be deterministic
/// - They help debug failing tests: they're more organized than the console (the compiled C is
///   built without debug info, though)
///
/// Snapshots are saved under `server/src/test/snapshots`. Only the `stdlib_*` examples' are
/// committed, in git LFS, without build products (`server/.gitignore`); the others are
/// regenerated by every run, including CI's, which therefore compares them against nothing from
/// an earlier commit. `.lfsconfig` keeps a clone and a pull from downloading the committed ones:
/// they're checked out as LFS pointers, which [SnapshotStore] treats like missing snapshots.
///
/// To investigate a regression in a `stdlib_*` example, fetch its baselines, then run the tests:
///
/// ```sh
/// git lfs pull --include="server/src/test/snapshots/**" --exclude=""
/// git config diff.lfs.textconv cat  # once, so `git diff` shows the content, not the pointer
/// ```
///
/// A run overwrites the fetched snapshots, so `git status` lists the ones whose content changed
/// and `git diff` shows how. Commit the changed snapshots together with the change that
/// intentionally alters them: committing them separately leaves the baselines stale, and every
/// later comparison reports a regression. Each refresh adds another copy to LFS storage, so
/// don't refresh for cosmetic changes alone.
